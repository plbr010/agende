const lf = (file) => readFileSync(`supabase/migrations/${file}.sql`, "utf8").replace(/\r\n/g, "\n");
const sha = (text) => createHash("sha256").update(text).digest("hex");

export function buildRollout({ commit = true } = {}) {
  const versions = PRODUCTION_PENDING.map((file) => file.slice(0, 14));
  let sql = [
    "-- Generated by scripts/build-production-rollout.mjs. Requires explicit owner approval.",
    "begin;",
    "set local lock_timeout = '10s';",
    "set local statement_timeout = '180s';",
    "do $pre$ begin",
    `  if exists (select 1 from supabase_migrations.schema_migrations where version = any (array[${versions.map((v) => `'${v}'`).join(",")}])) then`,
    "    raise exception 'rollout_precondition: a pending version is already in the ledger; stop and review';",
    "  end if;",
    "end $pre$;",
    // Backfills touch salons whose subscription expired. This documented
    // switch skips only the entitlement trigger, only in this transaction.
    "select set_config('app.bypass_entitlement','on',true);",
    "",
  ].join("\n");
  for (const file of PRODUCTION_PENDING) {
    const body = lf(file);
    const expected = PRODUCTION_PENDING_SHA256[file];
    if (expected && sha(body) !== expected) throw new Error(`checksum mismatch: ${file}`);
    if (/^\s*(begin|commit|rollback)\s*;/im.test(body)) throw new Error(`transaction statement inside ${file}`);
    const version = file.slice(0, 14);
    const name = file.slice(15);
    const tag = `$mig${version}$`;
    sql += `\n-- >>> ${file} sha256=${sha(body)}\n${body}\n;\n`;
    sql += `insert into supabase_migrations.schema_migrations(version,name,statements) values ('${version}','${name}',array[${tag}${body}${tag}]);\n`;
  }
  sql += "\nselect set_config('app.bypass_entitlement','off',true);\n";
  sql += commit ? "commit;\n" : "rollback;\n";
  return sql;
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/").replace(/^(?=[A-Za-z]:)/, "/")}`) {
  const [out, flag] = process.argv.slice(2);
  if (!out) throw new Error("usage: node scripts/build-production-rollout.mjs <output.sql> [--rollback]");
  const sql = buildRollout({ commit: flag !== "--rollback" });
  writeFileSync(out, sql);
  for (const file of PRODUCTION_PENDING) console.log(sha(lf(file)), file);
  console.log(`${PRODUCTION_PENDING.length} migrations, ${sql.length} bytes -> ${out}`);
}
